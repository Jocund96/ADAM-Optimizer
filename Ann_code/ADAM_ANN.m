% Output = trained weights, biases and losses + the final prediction of X 
%Input = function to optimize + layers + epochs + learning rate 

function [results, losses] = ADAM_ANN(x, Y, layers, num_epochs, activation, learning_rate)

activation = 'egal';

%% ===== Split the data into sets
% ---- Used a standard 70/15/15 split
[iTr, iVa, iTe] = split_data(numel(x), 0.70, 0.15);   % rest (15%) = test

xTr = x(iTr);  YTr = Y(iTr);
xVa = x(iVa);  YVa = Y(iVa);
xTe = x(iTe);  YTe = Y(iTe);

% Scale x to [-1, 1] using the Training data only
% then apply the very same scaling to validation and test data.
xMin = min(xTr);  xMax = max(xTr);
XTr = Scale(xTr, xMin, xMax);
XVa = Scale(xVa, xMin, xMax);
XTe = Scale(xTe, xMin, xMax);

fprintf("Data set segrated with %u training, %u validation and %u testing samples", numel(XTr),numel(XVa),numel(XTe));

%% === Train (Using training and validation data)
[params, trainLoss, valLoss] = train_adam(XTr, YTr, XVa, YVa, layers, num_epochs, learning_rate);

%% === Check the network on the Test set
mean_testLoss = mean((forward_propagate(XTe, params) - YTe).^2);
mean_trainLoss = mean((forward_propagate(XTr, params) - YTr).^2);
fprintf('\nFinal MSE train: %0.5f  val: %0.5f  test: %0.5f\n', ...
    mean_trainLoss, min(valLoss), mean_testLoss);

%% === The results of the function generated by the ANN
xFine = linspace(min(x), max(x), 1000);
yFine = forward_propagate(Scale(xFine, xMin, xMax), params);

%% === Return the data
results.params = params;
results.xFine = xFine;
results.yFine = yFine;

losses.trainLoss = trainLoss;
losses.valLoss = valLoss;
losses.testLoss = mean_testLoss;

fprintf('=== ANN training complete ===');

end


% Local Function definitions for the script

function [best_params, trainLoss, valLoss] = train_adam(XTr, YTr, XVa, YVa, layers, num_epochs, learning_rate)

% Initialisierung
params = init_params(layers);

% ADAM Parameters
beta1 = 0.9;
beta2 = 0.999;
eps = 1e-8;

% Initialisiere Moment-Schätzer  (Moment-estimator)
[m, v] = init_adam(params);

% Validation logic (Choose the best weights)
trainLoss = zeros(num_epochs,1);
valLoss   = zeros(num_epochs,1);
bestVal   = inf;

for epoch = 1:num_epochs

    % Vorwärtspropagation
    [A, cache] = forward_propagate(XTr, params);

    % Verlust (MSE)
    trainLoss(epoch) = mean((A - YTr).^2);

    % Rückwärtspropagation
    grads = back_propagate(XTr, YTr, params, cache);

    % ADAM Update
    [params, m, v] = adam_update(params, grads, m, v, epoch, learning_rate, beta1, beta2, eps);

    % check the validation loss without any training on it
    valLoss(epoch) = mean((forward_propagate(XVa, params) - YVa).^2);  

    % remember best weights and output them
    if valLoss(epoch) < bestVal                                     
        bestVal = valLoss(epoch);
        best_params    = params;
    end

    if mod(epoch,1000) == 0
        fprintf('Epoch %d, train Loss: %.4f val loss: %0.5f\n', epoch, trainLoss(epoch), valLoss(epoch));
    end
end
end

%% Initialisierung der Parameter
function params = init_params(layers)
for i = 1:length(layers)-1
    %params.(['W' num2str(i)]) = randn(layers(i+1), layers(i)) * 0.1;
    %params.(['b' num2str(i)]) = zeros(layers(i+1),1);
    params.(['W' num2str(i)]) = randn(layers(i+1), layers(i));   % no * 0.01
    params.(['b' num2str(i)]) = randn(layers(i+1), 1);           % random, not zeros
end
end

%% Initialisierung ADAM Variablen
function [m, v] = init_adam(params)
fields = fieldnames(params);
for i = 1:length(fields)
    m.(fields{i}) = zeros(size(params.(fields{i})));
    v.(fields{i}) = zeros(size(params.(fields{i})));
end
end

%% Vorwärtspropagation
function [A, cache] = forward_propagate(X, params)
W1 = params.W1; b1 = params.b1;
W2 = params.W2; b2 = params.b2;

Z1 = W1 * X + b1;
A1 = tanh(Z1); % tanh

Z2 = W2 * A1 + b2;
A = Z2; % lineare Ausgabe

cache = struct('X',X,'Z1',Z1,'A1',A1);
end

%% Rückwärtspropagation
function grads = back_propagate(X, Y, params, cache)

W2 = params.W2;

A1 = cache.A1;
A = params.W2 * A1 + params.b2;

%dZ2 = 2*(A - Y) / m;
dZ2 = 2*(A - Y) / numel(Y);
grads.W2 = dZ2 * A1';
grads.b2 = sum(dZ2,2);

dA1 = W2' * dZ2;
dZ1 = dA1 .* (1 - A1.^2); % tanh Ableitung

grads.W1 = dZ1 * X';
grads.b1 = sum(dZ1,2);
end

%% ADAM Update
function [params, m, v] = adam_update(params, grads, m, v, t, lr, beta1, beta2, eps)
fields = fieldnames(params);

for i = 1:length(fields)
    key = fields{i};

    % 1. Moment (Mean)
    m.(key) = beta1 * m.(key) + (1 - beta1) * grads.(key);

    % 2. Moment (Varianz)
    v.(key) = beta2 * v.(key) + (1 - beta2) * (grads.(key).^2);

    % Bias-Korrektur
    m_hat = m.(key) / (1 - beta1^t);
    v_hat = v.(key) / (1 - beta2^t);

    % Update
    params.(key) = params.(key) - lr * m_hat ./ (sqrt(v_hat) + eps);
end

end

function [scale] = Scale(x, xMin, xMax)
scale = 2*(x - xMin)/(xMax - xMin) - 1;
end

