% Output = trained weights, biases and losses + the final prediction of X 
% Input = function to optimize + layers + epochs + learning rate 

function [results, losses] = ADAM_ANN(x, Y, config)

%% ===== Split the data into sets
% ---- Used a standard 70/15/15 split
N = size(x, 2);
[iTr, iVa, iTe] = split_data(N, 0.70, 0.15);

xTr = x(:, iTr);  YTr = Y(:, iTr);
xVa = x(:, iVa);  YVa = Y(:, iVa);
xTe = x(:, iTe);  YTe = Y(:, iTe);

xMin = min(xTr, [], 2);  xMax = max(xTr, [], 2);     % per input row
XTr = Scale(xTr, xMin, xMax);
XVa = Scale(xVa, xMin, xMax);
XTe = Scale(xTe, xMin, xMax);

yMu = mean(YTr, 2);  ySd = std(YTr, 0, 2);           % per output row
YTrS = (YTr - yMu) ./ ySd;
YVaS = (YVa - yMu) ./ ySd;
YTeS = (YTe - yMu) ./ ySd;

fprintf("Data set segrated with %u training, %u validation and %u testing samples\n", numel(XTr),numel(XVa),numel(XTe));

%% === Train (Using training and validation data)
[params, trainLoss, time, valLoss] = train_adam(XTr, YTrS, XVa, YVaS, config);

%% === Check the network on the test set
% Scaled MSE: comparable across functions (1.0 = no better than predicting the mean)
mean_testLoss  = mean((forward_propagate(XTe, params, config.activation) - YTeS).^2);
mean_trainLoss = mean((forward_propagate(XTr, params, config.activation) - YTrS).^2);
% MSE in the original units of Y
yTePred = forward_propagate(XTe, params, config.activation) * ySd + yMu;
mean_testLoss_orig = mean((yTePred - YTe).^2);

fprintf('\nFinal scaled MSE  train: %0.5f  val: %0.5f  test: %0.5f\n', ...
    mean_trainLoss, min(valLoss), mean_testLoss);
fprintf('Test MSE in original units of Y: %0.5g\n', mean_testLoss_orig);

%% === The results of the function generated by the ANN
xFine = linspace(min(x), max(x), 1000);
yFine = forward_propagate(Scale(xFine, xMin, xMax), params, config.activation) * ySd + yMu;

%% === Return the data
results.params = params;
results.xFine = xFine;
results.yFine = yFine;
results.time         = time;                % cumulative seconds, per epoch

losses.trainLoss    = trainLoss;            % scaled
losses.valLoss      = valLoss;              % scaled
losses.testLoss     = mean_testLoss;        % scaled
losses.testLossOrig = mean_testLoss_orig;   % original units

end


% Local Function definitions for this script

function [best_params, trainLoss, time, valLoss] = train_adam(XTr, YTr, XVa, YVa, config)

% Initialisierung
params = init_params(config.layers);
state  = [];                                    % optimizer memory (m, v, ...)

% ADAM Parameters
hp.beta1 = 0.9;
hp.beta2 = 0.999;
hp.epsilon = 1e-8;
hp.learning_rate = config.hp.learning_rate;

% Validation logic (Choose the best weights)
trainLoss = zeros(config.num_epochs,1);
valLoss   = zeros(config.num_epochs,1);
bestVal   = inf;
best_params = params;
time      = nan(config.num_epochs,1);

t0 = tic;
fprintf('=== ANN training STARTED ===\n');

for epoch = 1:config.num_epochs

    % Vorwärtspropagation
    [A, cache] = forward_propagate(XTr, params, config.activation);

    % Verlust (MSE)
    trainLoss(epoch) = mean((A - YTr).^2);

    % Rückwärtspropagation
    grads = back_propagate(XTr, YTr, params, cache, config.activation);

    % ADAM Update
    %[params, m, v] = adam_update(params, grads, m, v, epoch, learning_rate, beta1, beta2, eps);
    [params, state] = config.optimizer(params, grads, state, epoch, hp);

    % check the validation loss without any training on it
    valLoss(epoch) = mean((forward_propagate(XVa, params, config.activation) - YVa).^2);

    % remember best weights and output them
    if valLoss(epoch) < bestVal
        bestVal     = valLoss(epoch);
        best_params = params;
    end
    
    time(epoch) = toc(t0);

    if mod(epoch,1000) == 0
        fprintf('Epoch %d, train Loss: %.4f val loss: %0.5f\n', epoch, trainLoss(epoch), valLoss(epoch));
    end
end
fprintf('=== ANN training COMPLETE ===\n');
end

%% Initialisierung der Parameter
function params = init_params(layers)
for i = 1:length(layers)-1
    %params.(['W' num2str(i)]) = randn(layers(i+1), layers(i)) * 0.1;
    %params.(['b' num2str(i)]) = zeros(layers(i+1),1);
    params.(['W' num2str(i)]) = randn(layers(i+1), layers(i));   % no * 0.01
    params.(['b' num2str(i)]) = randn(layers(i+1), 1);           % random, not zeros
end
end

%% Activation function swapping mechanism
function A = activate(Z, activation)
switch activation
    case 'tanh',      A = tanh(Z);
    case 'relu',      A = max(0, Z);
    case 'linear',    A = Z;
    case 'sigmoid',   A = 1 ./ (1 + exp(-Z));
    case 'leakyrelu', A = max(0.01*Z, Z);
    case 'elu',       A = Z;  A(Z <= 0) = exp(Z(Z <= 0)) - 1;
    case 'softplus',  A = max(Z, 0) + log1p(exp(-abs(Z)));   % overflow-safe
    case 'swish',     A = Z ./ (1 + exp(-Z));
    otherwise, error('Unknown activation "%s"', activation);
end
end

function dA = activate_derivative(Z, A, activation)
switch activation
    case 'tanh',      dA = 1 - A.^2;
    case 'relu',      dA = double(Z > 0);
    case 'linear',    dA = ones(size(Z));
    case 'sigmoid',   dA = A .* (1 - A);
    case 'leakyrelu', dA = ones(size(Z));  dA(Z <= 0) = 0.01;
    case 'elu',       dA = ones(size(Z));  dA(Z <= 0) = A(Z <= 0) + 1;
    case 'softplus',  dA = 1 ./ (1 + exp(-Z));
    case 'swish',     s = 1 ./ (1 + exp(-Z));  dA = s + Z .* s .* (1 - s);
end
end

%% Vorwärtspropagation
function [A, cache] = forward_propagate(X, params, activation)
L = numel(fieldnames(params)) / 2;          % number of weight layers
cache.A = cell(L+1, 1);                     % A{1} = input, A{L+1} = output
cache.Z = cell(L, 1);
cache.A{1} = X;
for i = 1:L
    W = params.(sprintf('W%d',i));
    b = params.(sprintf('b%d',i));
    cache.Z{i} = W * cache.A{i} + b;
    if i < L
        cache.A{i+1} = activate(cache.Z{i}, activation);   % hidden layer
    else
        cache.A{i+1} = cache.Z{i};                          % linear output
    end
end
A = cache.A{L+1};
end

%% Rückwärtspropagation
function grads = back_propagate(X, Y, params, cache, activation)
L = numel(fieldnames(params)) / 2;
dZ = 2*(cache.A{L+1} - Y) / numel(Y);       % adjoint at the output
for i = L:-1:1
    grads.(sprintf('W%d',i)) = dZ * cache.A{i}';
    grads.(sprintf('b%d',i)) = sum(dZ, 2);
    if i > 1                                % pass the adjoint one layer back
        dA = params.(sprintf('W%d',i))' * dZ;
        dZ = dA .* activate_derivative(cache.Z{i-1}, cache.A{i}, activation);
    end
end
end

function [scale] = Scale(x, xMin, xMax)
scale = 2*(x - xMin)/(xMax - xMin) - 1;
end


function [iTr, iVa, iTe] = split_data(N, pTrain, pVal)
idx = randperm(N);                        % shuffle 1..N
nTr = round(pTrain * N);
nVa = round(pVal   * N);
iTr = sort(idx(1 : nTr));                 % training indices
iVa = sort(idx(nTr+1 : nTr+nVa));         % validation indices
iTe = sort(idx(nTr+nVa+1 : end));         % test indices (the rest)
end
